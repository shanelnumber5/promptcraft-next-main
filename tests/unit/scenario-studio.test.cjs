const assert=require('node:assert/strict');
(async()=>{
 const {initialState,saveState,loadState,STORAGE_KEY}=await import('../../src/app/storage.js');
 const {discussionOpening}=await import('../../src/features/opening/content.js');
 const {readScenarioStudio,saveScenarioStudio,resetScenarioStudio,SCENARIO_STUDIO_KEY}=await import('../../src/features/workspace/scenario-storage.js');
 const {WORKSPACE_KEY}=await import('../../src/features/workspace/storage.js');
 const {assignmentContext}=await import('../../src/features/design/babbage-client.js');
 const {finalCheckContext,finalCheckReady}=await import('../../src/features/design/content.js');
 const {createProjectFile,parseProjectFile}=await import('../../src/features/workspace/project-file.js');
 const {renderWorkspace}=await import('../../src/features/workspace/screen.js');
 const {renderClosing}=await import('../../src/features/design/closing.js');
 const {createGuide}=await import('../../src/features/design/guide.js');
 const records=new Map([[WORKSPACE_KEY,'independent workspace']]);
 const storage={getItem:k=>records.get(k)||null,setItem:(k,v)=>records.set(k,v),removeItem:k=>records.delete(k)};
 assert(readScenarioStudio(storage).needsIntro,'New educators still enter the scenario introduction');
 for(const phase of ['setup','summary']) {
  const legacy=initialState(discussionOpening);legacy.phase=phase;legacy.teacher.directions='Keep this entered assignment.';
  saveState(legacy,storage);
  const migrated=readScenarioStudio(storage);
  assert(!migrated.needsIntro && !migrated.error,'Legacy intake resumes in the shared forms');
  assert.equal(migrated.designPage,'start');assert.equal(migrated.state.designPanel,'revision');
  assert.equal(migrated.state.teacher.directions,legacy.teacher.directions);
 }
 const main=initialState(discussionOpening);
 main.phase='design';main.designStep=2;main.designPanel='revision';
 Object.assign(main.teacher,{directions:'Discuss staffing choices.',learningGoal:'Defend a staffing choice using evidence.',aiUse:'No AI'});
 Object.assign(main.design,{sourceDirections:main.teacher.directions,revision:'Compare two schedules and defend a decision.',reason:'Practice using evidence.',instructorPlan:'Ask a content-specific question.',feedbackClarifications:'Keep asynchronous participation.'});
 main.babbage.context=assignmentContext(main);
 main.babbage.history=[{role:'assistant',display:'An earlier guided suggestion.',content:'{"message":"An earlier guided suggestion."}'}];
 saveState(main,storage);
 const restored=readScenarioStudio(storage);
 assert(!restored.error && !restored.needsIntro);
 const state=restored.state;
 assert.equal(state.experience,'scenario');
 assert.equal(state.design.revision,main.design.revision);
 assert.equal(state.workspace.instructorPlan,main.design.instructorPlan);
 assert.equal(state.workspace.openQuestions,main.design.feedbackClarifications);
 assert.equal(state.babbage.history[0].display,'An earlier guided suggestion.','Migration preserves the validated prior conversation');
 state.designPanel='reason';state.workspace.instructorPlan='Question students’ reasoning and respond to a misconception.';
 state.design.instructorPlan=state.workspace.instructorPlan;
 Object.assign(state.finalCheck,{context:finalCheckContext(state.teacher,state.design),instructions:true,learning:true,requirements:true,approved:true,completed:true});
 assert(finalCheckReady(state));
 state.babbage.context=assignmentContext(state);
 assert(saveScenarioStudio(state,storage));
 assert.equal(records.get(WORKSPACE_KEY),'independent workspace');
 const resumed=readScenarioStudio(storage);
 assert.equal(resumed.state.workspace.instructorPlan,state.workspace.instructorPlan);
 assert.equal(resumed.state.finalCheck.approved,true,'Approved design survives reload with its instructor plan');
 assert.equal(resumed.state.babbage.history.length,1,'Shared-controller history survives later reloads');
 const savedMain=loadState(discussionOpening,storage);
 assert.equal(savedMain.design.instructorPlan,state.workspace.instructorPlan);
 assert(!Object.hasOwn(JSON.parse(records.get(STORAGE_KEY)),'workspace'),'The main scenario save retains its original shape');
 const backup=parseProjectFile(createProjectFile(state));assert.equal(backup.experience,'scenario');
 assert.equal(backup.workspace.instructorPlan,state.workspace.instructorPlan);
 for(const page of ['start','subject','ai-use','intentions','presence','draft']) {
  const html=renderWorkspace({...state,designPanel:'revision'},{pending:false,configured:true},'',page);
  assert(html.includes('Scenario 1 · Design your activity'));
  assert(html.includes('workspace-section-sidebar') && html.includes('workspace-action-bar'));
  assert.equal((html.match(/id="workspace-tab-/g)||[]).length,3,'Scenario uses the same three stage controls');
 }
 const checks=renderWorkspace(state,{pending:false,configured:true},'','draft','work','checks');
 assert(checks.includes('data-action="preview-guide"') && checks.includes('data-action="download-guide"'));
 assert(checks.includes('Finish with Pixel'));
 const guide=createGuide(state.design,{teacher:state.teacher,approved:true});assert(guide.includes('The lemonade example'));
 state.phase='closing';assert(saveScenarioStudio(state,storage));assert(readScenarioStudio(storage).wrapUp);
 assert(renderClosing(state).includes('Module complete'),'Scenario retains its module completion');
 assert(renderClosing(state).includes('data-action="closing-pixel"'),'Recap leads to Pixel');
 const pixelClosing=renderClosing(state,'dialogue');
 assert(pixelClosing.includes('focus--dialogue'),'Pixel appears in the established dialogue scene');
 assert(pixelClosing.includes('Professor Pixel'));
 assert(pixelClosing.includes('Your learning goal is'));
 assert(pixelClosing.includes('data-action="preview-guide"'),'Pixel closes with the guide action');
 assert(!pixelClosing.includes('data-action="closing-pixel"'),'Closing does not loop back into itself');
 const oldMain=records.get(STORAGE_KEY);records.set(SCENARIO_STUDIO_KEY,'{broken');
 assert(readScenarioStudio(storage).error);assert.equal(records.get(STORAGE_KEY),oldMain);
 assert.equal(records.get(SCENARIO_STUDIO_KEY),'{broken');
 assert(resetScenarioStudio(storage));assert(!records.has(STORAGE_KEY) && !records.has(SCENARIO_STUDIO_KEY));
 assert.equal(records.get(WORKSPACE_KEY),'independent workspace','Restarting Scenario 1 never clears the private Workspace');
 records.set(STORAGE_KEY,'{broken main');
 assert(readScenarioStudio(storage).error);assert.equal(records.get(STORAGE_KEY),'{broken main','Corrupt main scenario progress is not rewritten');
 const fail={getItem:()=>null,setItem:()=>{throw Error('quota');}};
 assert(!saveScenarioStudio(state,fail) && state.saveNotice.includes('backup'));
 console.log('PASS: shared scenario studio, legacy migration, separate saves, history/approval restoration, six Build pages, guide actions, backup identity, completion, corruption and reset isolation. Offline only.');
})().catch(e=>{console.error(e);process.exitCode=1;});
