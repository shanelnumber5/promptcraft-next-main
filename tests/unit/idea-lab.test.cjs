const assert = require('node:assert/strict');
(async () => {
  const { ideas, filterIdeas, findIdea } = await import('../../src/features/idea-lab/ideas.js');
  const { freshWorkspace, saveWorkspace, readWorkspace, resetWorkspace, rememberPath, resumePath, WORKSPACE_KEY } = await import('../../src/features/workspace/storage.js');
  const { STORAGE_KEY, initialState, saveState } = await import('../../src/app/storage.js');
  const { discussionOpening } = await import('../../src/features/opening/content.js');
  const records = new Map();
  const storage = { getItem: key => records.get(key) || null, setItem: (key, value) => records.set(key, value), removeItem: key => records.delete(key) };
  assert.equal(ideas.length, 12);
  assert.equal(new Set(ideas.map(idea => idea.id)).size, 12);
  for (const idea of ideas) assert(idea.title && idea.summary && idea.purpose && idea.actions.length && idea.contexts && idea.tags.length);
  assert(filterIdeas('variations that do not exist').length === 0);
  assert(filterIdeas('', 'Responsible AI').length === 2);
  assert(filterIdeas('workplace').some(idea => idea.id === 'shift-change'));
  assert.equal(findIdea('not-real'), undefined);
  assert.equal(resumePath(storage), '');
  const guided = initialState(discussionOpening);
  guided.answers = { test: 'preserve this raw guided snapshot' };
  saveState(guided, storage);
  const guidedRaw = records.get(STORAGE_KEY);
  const state = freshWorkspace();
  state.teacher.directions = 'A rough idea about fair staffing';
  state.design.sourceDirections = state.teacher.directions;
  state.design.revision = 'Compare two staffing options.';
  state.workspace.sourceKind = 'idea';
  state.workspace.ideaId = 'shift-change';
  assert(saveWorkspace(state, storage));
  assert.equal(readWorkspace(storage).state.design.revision, state.design.revision);
  assert.equal(readWorkspace(storage).state.workspace.ideaId, 'shift-change');
  assert.equal(records.get(STORAGE_KEY), guidedRaw, 'Workspace saves never change guided progress');
  rememberPath('workspace', storage);
  assert.equal(resumePath(storage), 'workspace');
  assert(resetWorkspace(storage));
  assert.equal(resumePath(storage), 'play');
  assert.equal(records.get(STORAGE_KEY), guidedRaw);
  records.set(WORKSPACE_KEY, '{broken');
  assert(readWorkspace(storage).error);
  assert.equal(records.get(WORKSPACE_KEY), '{broken', 'Unreadable records are not silently replaced');
  const blocked = { getItem: () => { throw Error('blocked'); }, setItem: () => { throw Error('quota'); } };
  assert.equal(saveWorkspace(state, blocked), false);
  assert(state.saveNotice.includes('could not save'));
  assert(readWorkspace(blocked).error);
  console.log('PASS: 12 illustrative ideas, search/filtering, separate workspace saves, resume selection, reset isolation, malformed records and save failures.');
})().catch(error => { console.error(error); process.exitCode = 1; });
