const assert = require('node:assert/strict');
(async () => {
  const { ideas, filterIdeas, findIdea } = await import('../../src/features/idea-lab/ideas.js');
  const { freshWorkspace, saveWorkspace, readWorkspace, resetWorkspace, rememberPath, resumePath, WORKSPACE_KEY } = await import('../../src/features/workspace/storage.js');
  const { STORAGE_KEY, initialState, saveState } = await import('../../src/app/storage.js');
  const { discussionOpening } = await import('../../src/features/opening/content.js');
  const records = new Map();
  const storage = { getItem: key => records.get(key) || null, setItem: (key, value) => records.set(key, value), removeItem: key => records.delete(key) };
  assert.equal(ideas.length, 12);
  assert.equal(new Set(ideas.map(idea => idea.id)).size, 12);
  for (const idea of ideas) {
    assert(idea.title && idea.summary && idea.purpose && idea.actions.length && idea.contexts && idea.tags.length);
    assert(idea.tags.includes('Discussion'), `${idea.id} is identified as a forum discussion`);
    assert.match(idea.actions[0], /^Post\b/);
    assert.match(idea.actions[1], /^Reply\b/);
    assert.match(idea.actions[2], /^Follow up\b/);
  }
  assert(filterIdeas('variations that do not exist').length === 0);
  assert(filterIdeas('', 'Responsible AI').length === 2);
  assert(filterIdeas('workplace').some(idea => idea.id === 'shift-change'));
  assert.equal(findIdea('not-real'), undefined);
  assert.equal(resumePath(storage), '');
  const guided = initialState(discussionOpening);
  guided.answers = { test: 'preserve this raw guided snapshot' };
  saveState(guided, storage);
  const guidedRaw = records.get(STORAGE_KEY);
  const state = freshWorkspace();
  state.teacher.directions = 'A rough idea about fair staffing';
  state.design.sourceDirections = state.teacher.directions;
  state.design.revision = 'Compare two staffing options.';
  state.workspace.sourceKind = 'idea';
  state.workspace.ideaId = 'shift-change';
  assert(saveWorkspace(state, storage));
  assert.equal(readWorkspace(storage).state.design.revision, state.design.revision);
  assert.equal(readWorkspace(storage).state.workspace.ideaId, 'shift-change');
  assert.equal(records.get(STORAGE_KEY), guidedRaw, 'Workspace saves never change guided progress');
  rememberPath('workspace', storage);
  assert.equal(resumePath(storage), 'workspace');
  assert(resetWorkspace(storage));
  assert.equal(resumePath(storage), 'play');
  assert.equal(records.get(STORAGE_KEY), guidedRaw);
  records.set(WORKSPACE_KEY, '{broken');
  assert(readWorkspace(storage).error);
  assert.equal(records.get(WORKSPACE_KEY), '{broken', 'Unreadable records are not silently replaced');
  const blocked = { getItem: () => { throw Error('blocked'); }, setItem: () => { throw Error('quota'); } };
  assert.equal(saveWorkspace(state, blocked), false);
  assert(state.saveNotice.includes('could not save'));
  assert(readWorkspace(blocked).error);
  const { buildBabbageRequest, assignmentContext } = await import('../../src/features/design/babbage-client.js');
  const { buildMayaRequest } = await import('../../src/features/design/maya-client.js');
  const { createGuide } = await import('../../src/features/design/guide.js');
  const { renderWorkspace } = await import('../../src/features/workspace/screen.js');
  const { renderHome } = await import('../../src/features/entry/screen.js');
  const { renderGallery, renderIdeaDetail } = await import('../../src/features/idea-lab/screen.js');
  state.teacher.learningGoal = 'Explain a fair staffing decision.';
  state.design.reason = 'Compare tradeoffs and look for a supported choice.';
  state.babbage.context = assignmentContext(state);
  state.babbage.mode = 'dev';
  state.babbage.ready = true;
  saveWorkspace(state, storage);
  const restored = readWorkspace(storage).state;
  assert.equal(restored.babbage.ready, true, 'Workspace context restores through the existing validator');
  const body = buildBabbageRequest(state, 'revise');
  assert.equal(body.analysis_type, 'scenario1');
  assert(body.system.includes('This prototype supports discussion forum activities only'));
  assert.equal(JSON.parse(body.messages[0].content).workspace.idea.id, 'shift-change');
  assert(buildMayaRequest(state).system.includes('not an earlier assignment students completed'));
  const { mayaContext } = await import('../../src/features/design/maya-client.js');
  const beforeNeeds = mayaContext(state);
  state.workspace.studentNeeds = 'Flexible timing';
  assert.notEqual(mayaContext(state), beforeNeeds, 'Changed learner needs invalidate a cached student reading');
  const guide = createGuide(state.design, { teacher: state.teacher, workspace: state.workspace });
  assert(guide.includes('Your starting idea'));
  assert(guide.includes('Your chosen assignment design'));
  assert(guide.includes('Shift-Change Challenge'));
  assert(!guide.includes('id="lemonade-example"'));
  assert(!guide.includes('Scenario 1 ·'));
  state.workspace.sourceKind = 'existing';
  assert(createGuide(state.design, { teacher: state.teacher, workspace: state.workspace }).includes('Your original assignment'));
  const pendingGuide = createGuide({ ...state.design, revision: '', reason: '' }, { teacher: state.teacher, workspace: state.workspace, approved: false });
  assert(pendingGuide.includes('Use the Design tab'));
  assert(!pendingGuide.includes('Return to Design one focused discussion-board activity'));
  const home = renderHome('workspace');
  assert(home.includes('Continue Where You Left Off'));
  assert(home.includes('Design a Discussion'));
  assert(home.includes('forum exchange purposeful'));
  assert(home.includes('class="river-note"'));
  assert(home.includes('class="entry-footnote" aria-label="Privacy and progress information"'));
  const gallery = renderGallery();
  assert(gallery.includes('class="gallery-kicker">Discussion forum ideas</span>'));
  assert(gallery.includes('Browse discussion forum ideas. Make one your own.'));
  assert(gallery.includes('class="gallery-intro-row"'));
  assert(gallery.includes('12 illustrative starters'));
  assert(gallery.includes('other activity types can have their own space'));
  assert(renderIdeaDetail('failure-file').includes('Discussion forum flow'));
  assert(renderIdeaDetail('shift-change', true).includes('Your starting material and draft stay intact'));
  assert(renderWorkspace(state, { configured: true }).includes('Create a Discussion Forum'));
  records.set(STORAGE_KEY, '{broken-guided');
  assert.equal(resumePath(storage), 'workspace', 'A malformed guided save cannot hide a valid workspace');
  console.log('PASS: 12 illustrative ideas, search/filtering, separate workspace saves, resume selection, reset isolation, malformed records and save failures.');
})().catch(error => { console.error(error); process.exitCode = 1; });
