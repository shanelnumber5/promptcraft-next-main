  fitWorkspace({querySelector:()=>shell},{innerHeight:900,scrollY:0});
  assert.equal(measuredHeight,'764px', 'Scrolling does not change the frame height');
  fitWorkspace({querySelector:()=>shell},{innerHeight:768,scrollY:0});
  assert.equal(measuredHeight,'632px', 'Fullscreen/resize recomputes available height');
  fitWorkspace({querySelector:()=>null},{innerHeight:768,scrollY:0});
  const screen=renderWorkspace(state,{pending:false,configured:true});
  assert(screen.indexOf('class="workspace-messages"')<screen.indexOf('id="workspace-panel"'), 'Notices have a reserved row above the panel');
