  html = renderReview(state,{pending:false},'rationale');
  assert(html.includes('Babbage is reviewing your design'), 'Review-specific pending state is visible');
  assert(html.includes('aria-busy="true"'));
  assert(!html.includes('data-action="check-workspace-revision"'));
  assert(!html.includes('data-action="continue-to-maya"'), 'Maya waits for the review request');
  assert(!html.includes('Your first review will begin automatically.'));
  assert(html.includes('data-action="edit-draft"'), 'Edit activity returns to the working draft');
  assert(html.indexOf('workspace-ai-disclosure') < html.indexOf('workspace-review-feedback'));
  state.babbage.mode = 'dev';
  assert(renderReview(state,{pending:false},'rationale').includes('No AI analysis or API call.'));
  state.babbage.mode = 'live';
  state.creative.review.status = 'complete';
  const {renderPartner} = await import('../../src/features/workspace/partner-view.js');
  const {renderWorkspaceDisclosure} = await import('../../src/features/workspace/disclosure.js');
  for(const page of ['history','options','ideas']) {
    const partner = renderPartner(state,{pending:false,configured:true},page);
    assert.equal((partner.match(/<footer/g)||[]).length,1, `${page} has one footer`);
    assert(partner.includes(renderWorkspaceDisclosure(state)), `${page} uses the same disclosure`);
    assert(!partner.includes('workspace-view-actions'), `${page} actions stay outside scrolling content`);
    if(page==='ideas') assert(partner.indexOf('</div><footer class="workspace-action-bar partner-actions">')>0);
  }
  const {renderWorkspace}=await import('../../src/features/workspace/screen.js');
  const {buildPages,renderUtility}=await import('../../src/features/workspace/views.js');
  state.designPanel='revision';
  for(const [id] of buildPages) assert.equal((renderWorkspace(state,{pending:false,configured:true},'',id).match(/class="workspace-action-bar /g)||[]).length,1, `${id} has one anchored footer`);
  for(const id of ['rationale','reasoning','checks','guide','help']) {
    const markup=renderReview(state,{pending:false},id);
    assert.equal((markup.match(/class="workspace-action-bar /g)||[]).length,1);
    assert(!markup.includes('class="course-guide-actions"'), 'Guide tools do not create a second gold band');
  }
  assert(renderUtility(state,{pending:false},{screen:'options'}).includes('workspace-action-bar workspace-view-back'));
  assert(renderPartner(state,{pending:true,configured:true},'work').includes('workspace-action-bar partner-actions'), 'Loading retains the footer');
  state.designPanel='reason';
  const buildState=structuredClone(state);buildState.designPanel='revision';
  const requirements=renderWorkspace(buildState,{pending:false,configured:true},'', 'ai-use');
  assert(requirements.includes('class="workspace-field-wide" data-setup-form'), 'Requirements span the two-column grid');
  const course=renderWorkspace(buildState,{pending:false,configured:true},'', 'subject');
  for (const id of ['workTime','daysAvailable']) {
    assert(course.includes(`id="${id}"`), `${id} is on Course & learners`);
    assert(!requirements.includes(`id="${id}"`), `${id} is removed from requirements`);
  }
  assert(requirements.includes('AI-use instructions and limits'));
  const draftPage=renderWorkspace(buildState,{pending:false,configured:true},'', 'draft');
  assert(draftPage.includes('contenteditable="true"') && draftPage.includes('data-editor-command="bold"') && draftPage.includes('data-editor-style'), 'Workspace uses the rich text editor');
  assert(!draftPage.includes('<textarea id="revision"'), 'Raw markup is not displayed in a draft textarea');
  assert(draftPage.includes('data-action="review-my-design"'), 'Review explicitly requests reworking');
  assert(course.indexOf('id="daysAvailable"')<course.indexOf('workspace-course-long'), 'All short course fields are in the left column');
  assert(course.indexOf('id="learningGoal"')>course.indexOf('workspace-course-long'), 'Larger fields are on the right');
  assert(requirements.includes('workspace-field-help workspace-field-wide'), 'AI instructions span both columns');
  assert(renderPartner(buildState,{pending:true,configured:true},'work','',{task:'draft'}).includes('Develop your activity with Babbage'));
  const creative=renderWorkspace(buildState,{pending:false,configured:true},'', 'intentions');
  assert(creative.includes('workspace-stacked-fields'));
  assert(creative.indexOf('id="creative-core"')<creative.indexOf('id="concern"'), 'Optional improvement follows creative core');
  const presence=renderWorkspace(buildState,{pending:false,configured:true},'', 'presence');
  assert(presence.includes('workspace-stacked-fields'));
  assert(presence.indexOf('id="instructor-plan"')<presence.indexOf('id="open-questions"'));
  const explore=renderPartner(state,{pending:false,configured:true},'work');
  assert(explore.includes('<h2 class="workspace-build-title" id="ai-title"'), 'Explore has a visible page heading');
  const options=renderUtility(state,{pending:false,configured:true},{screen:'options'});
  assert(!options.includes('Workspace options'));
  assert(!options.includes('Shortcuts for your workspace'));
  assert(options.includes('aria-label="Project options"'));
  assert(!options.includes('data-review-page="guide"'), 'Guide remains in Review rather than duplicating options');
  assert(!options.includes('data-workspace-view="sections"') && !options.includes('href="?view=lab"'), 'Routine navigation is not duplicated');
  assert(!options.includes('<details'), 'Options has no accordion');
  const mainOptions=options.split('<nav class="workspace-welcome-choices"')[1];
  assert.equal((mainOptions.match(/data-action=/g)||[]).length,2, 'Only download and open project buttons are prominent');
  assert(mainOptions.includes('Save and leave'));
  assert(options.includes('workspace-project-menu'), 'Project options follow the main menu structure');
  assert(!options.includes('href="?view=guide"'), 'Workspace guide does not route to the separate guide library');
  for(const action of ['save-project-file','open-project-file']) assert(options.includes(`data-action="${action}"`), 'Backup controls remain available');
  const welcome=renderPartner(freshWorkspace(),{pending:false,configured:true},'work');
  assert(welcome.includes('workspace-welcome-board'));
  assert.equal((welcome.match(/data-action="edit-context"/g)||[]).length,1, 'One starting-point action on the welcome menu');
  const chosen=freshWorkspace();
  chosen.teacher.directions='Test a case-based decision.';
  chosen.workspace.selectedDirection={title:'Compare evidence',core:'Revise a decision.'};
  chosen.babbage.ready=false;
  const chosenHtml=renderPartner(chosen,{pending:false,configured:true},'work');
  assert(chosenHtml.includes('data-action="consult-babbage"'), 'Chosen ideas offer consultation before clarification is complete');
