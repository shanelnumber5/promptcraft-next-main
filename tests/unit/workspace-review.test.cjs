  assert(questionHtml.indexOf('data-action="send-clarification"')>questionHtml.indexOf('<footer'), 'Draft action is in the footer');
  assert(questionHtml.includes('Your current draft is unchanged'));
  questioning.design.revision=''; delete questioning.workspace.selectedDirection;
  assert(renderPartner(questioning,{pending:false,configured:true},'work','',{task:'draft'}).includes('data-action="send-clarification"'), 'An empty draft must not hide pending questions behind the welcome menu');
