const assert=require('node:assert/strict');
(async()=>{
 const {freshWorkspace,saveWorkspace,readWorkspace}=await import('../../src/features/workspace/storage.js');
 const {createProjectFile,parseProjectFile}=await import('../../src/features/workspace/project-file.js');
 const {feedbackQuestions,saveFeedbackAnswer,answerFor,savedFeedbackNotes}=await import('../../src/features/design/feedback-conversation.js');
 const {renderFeedbackClarifications}=await import('../../src/features/workspace/feedback-questions.js');
 const {createGuide}=await import('../../src/features/design/guide.js');
 const state=freshWorkspace();state.design.revision='Compare case evidence.';
 const scene={version:1,maya:{emotion:'thoughtful',text:'I would "Compare case evidence". Which case should I use?'},pixel:{emotion:'explaining',text:'"Compare case evidence" makes reasoning visible. What will you look for?'}};
 const questions=feedbackQuestions(scene);assert.equal(questions.length,2);
 Object.assign(state.creative.conversation,{draft:state.design.revision,response:JSON.stringify(scene),context:'current-context'});
 saveFeedbackAnswer(state,questions[0],'Use the supplied staffing case.');
 const before=state.design.revision;
 const records=new Map();const storage={setItem:(k,v)=>records.set(k,v),getItem:k=>records.get(k)||null};
 assert(saveWorkspace(state,storage));
 const restored=readWorkspace(storage).state;
 assert.equal(answerFor(restored,questions[0]),'Use the supplied staffing case.','Typed answers survive reload before any revision');
 const imported=parseProjectFile(createProjectFile(restored));
 assert.equal(answerFor(imported,questions[0]),'Use the supplied staffing case.','Answers survive project backup and import');
 assert(renderFeedbackClarifications(imported,false).includes('Use the supplied staffing case.'),'Legacy form links restore saved answers');
 saveFeedbackAnswer(imported,questions[1],'Look for a reason supported by case evidence.');
 assert(savedFeedbackNotes(imported).includes('Pixel: What will you look for?'));
 assert.equal(imported.design.revision,before,'Conversation answers never silently rewrite the draft');
 const html=createGuide(imported.design,{workspace:imported.workspace,teacher:imported.teacher,conversationNotes:savedFeedbackNotes(imported),approved:false});
 assert(!html.includes('Conversation decisions') && !html.includes('Educator:'));
 saveFeedbackAnswer(imported,questions[0],'<script>bad()</script>');
 assert(!renderFeedbackClarifications(imported,false).includes('<script>'));
 console.log('PASS: conversation question ownership, immediate save/reload, backup/import, legacy form restoration, draft preservation and guide notes. Offline only.');
})().catch(e=>{console.error(e);process.exitCode=1;});
