const assert = require('node:assert/strict');
(async () => {
  const { freshWorkspace, saveWorkspace, readWorkspace, WORKSPACE_KEY } = await import('../../src/features/workspace/storage.js');
  const { buildCreativeRequest, requestCreativeDirections, normalizeCreativeResponse, combineDirections, creativeBasis } = await import('../../src/features/workspace/creative.js');
  const { renderPossibilities, renderCreativeCore } = await import('../../src/features/workspace/creative-view.js');
  const { renderPartner } = await import('../../src/features/workspace/partner-view.js');
  const { finalCheckReady, finalCheckContext } = await import('../../src/features/design/content.js');
  const { buildBabbageRequest } = await import('../../src/features/design/babbage-client.js');
  const { createGuide } = await import('../../src/features/design/guide.js');
  const { initialState, STORAGE_KEY, saveState } = await import('../../src/app/storage.js');
  const { discussionOpening } = await import('../../src/features/opening/content.js');
  const fixtures = ['Investigate conflicting evidence', 'Negotiate competing priorities', 'Trace consequences across decisions'].map((experience, i) => ({ title: 'Direction ' + i, description: 'An illustrative sketch ' + i, experience, learning: 'Defend a decision with evidence', online: 'Asynchronous LMS exchange', core: 'Protect this mechanism ' + i }));
  const response = { analysis: { feedback_summary: JSON.stringify({ version: 1, directions: fixtures }) } };
  const state = freshWorkspace();
  state.teacher.directions = 'Replace an agreement-only discussion.';
  state.design.revision = 'My current draft';
  state.creative.feedback = 'Use our existing LMS.';
  const explorationCard = renderPossibilities(state, { configured: true, pending: false });
  assert(!explorationCard.includes('disabled'), 'A starting activity can be explored without a learning goal');
  // Test initial routing in an actually initial workspace, not one with a completed draft.
  const startingState = freshWorkspace();
  startingState.teacher.directions = state.teacher.directions;
  startingState.babbage.questions = [{ id: 'ai-use', text: 'What student AI use should this assignment allow?' }];
  const initialPartner = renderPartner(startingState, { configured: true, pending: false }, 'work');
  assert(initialPartner.includes('data-action="explore-directions"'), 'Initial exploration uses the creative workflow');
  assert(!initialPartner.includes('data-action="ask-ai"'), 'Initial exploration does not use general clarification');
  state.teacher.learningGoal = 'Defend decisions using evidence.';
  const before = JSON.stringify(state);
  let sent;
  const directions = await requestCreativeDirections(state, { fetchImpl: async (url, options) => { sent = JSON.parse(options.body); return { ok: true, json: async () => response }; } });
  assert.equal(JSON.stringify(state), before, 'Receiving possibilities cannot change the active design');
  assert.equal(sent.analysis_type, 'scenario1', 'Keep the existing service envelope');
  assert.equal(JSON.parse(sent.messages.at(-1).content).explore_three_directions, true, 'Mark the request as exploratory sketch generation');
  assert(sent.system.includes('genuinely different student actions'));
  assert(sent.system.includes('do not ask clarification questions'));
  assert(sent.system.includes('Do not require student AI-use policy'));
  assert(sent.system.includes('do not invent, imply, or silently finalize a learning objective'));
  assert(sent.system.includes('proactive guidance'), 'Explore sketches can consider instructor connection without a checklist');
  assert(sent.system.includes('Do not promise') || sent.system.includes('Do not invent compliance'), 'Do not certify RSI');
  assert.equal(JSON.parse(sent.messages.at(-1).content).educator_feedback, state.creative.feedback);
  assert.deepEqual(directions, fixtures);
  assert.throws(() => normalizeCreativeResponse({ analysis: { feedback_summary: 'a prose response' } }), /three readable/);
  assert.throws(() => normalizeCreativeResponse({ analysis: { feedback_summary: JSON.stringify({ version: 1, directions: [fixtures[0], fixtures[0], fixtures[1]] }) } }), /repeated/);
  assert.throws(() => normalizeCreativeResponse({ analysis: { feedback_summary: JSON.stringify({ version: 1, directions: [{...fixtures[0], core: ''}, fixtures[1], fixtures[2]] }) } }), /incomplete/);
  await assert.rejects(requestCreativeDirections(state, { fetchImpl: async () => ({ ok: false }) }), /unchanged/);
  const abort = new AbortController(); abort.abort();
  await assert.rejects(requestCreativeDirections(state, { signal: abort.signal, fetchImpl: async (url, options) => { options.signal.throwIfAborted(); } }), { name: 'AbortError' });
  assert.throws(() => combineDirections([fixtures[0]]), /at least two/);
  const combined = combineDirections([fixtures[0], fixtures[1]]);
  assert(combined.core.includes(fixtures[0].core) && combined.core.includes(fixtures[1].core));
  const basis = creativeBasis(state);
  state.teacher.mustStay = 'No new tools';
  assert.notEqual(creativeBasis(state), basis, 'Changed constraints invalidate an in-flight exploration');
  state.creative.directions = directions;
  state.creative.alternatives = [combined];
  state.creative.mayaPaused = true;
  state.workspace.selectedDirection = fixtures[0];
  state.workspace.creativeCore = 'My edited creative core';
  state.workspace.instructorPlan = 'Respond to initial reasoning and give final feedback.';
  state.workspace.openQuestions = 'Will this fit an hour?';
  const records = new Map();
  const storage = { getItem: key => records.get(key) || null, setItem: (key, value) => records.set(key, value) };
  saveState(initialState(discussionOpening), storage);
  const guided = records.get(STORAGE_KEY);
  assert(saveWorkspace(state, storage));
  const restored = readWorkspace(storage);
  assert.equal(restored.error, '');
  assert.deepEqual(restored.state.creative, state.creative);
  assert.equal(restored.state.workspace.creativeCore, 'My edited creative core');
  assert.equal(restored.state.design.revision, 'My current draft');
  assert.equal(records.get(STORAGE_KEY), guided, 'Creative saves preserve guided progress byte for byte');
  const legacy = JSON.parse(records.get(WORKSPACE_KEY));
  delete legacy.creative;
  delete legacy.workspace.selectedDirection;
  records.set(WORKSPACE_KEY, JSON.stringify(legacy));
  assert.equal(readWorkspace(storage).state.creative.alternatives.length, 0, 'Legacy workspace records load without rewriting');
  const legacyRaw = records.get(WORKSPACE_KEY);
  readWorkspace(storage);
  assert.equal(records.get(WORKSPACE_KEY), legacyRaw);
  const corrupt = {...legacy, creative: {directions: [{title: 'broken'}], alternatives: []}};
  records.set(WORKSPACE_KEY, JSON.stringify(corrupt));
  assert(readWorkspace(storage).error);
  assert.equal(records.get(WORKSPACE_KEY), JSON.stringify(corrupt), 'Unreadable creative work is never overwritten');
  const cards = renderPossibilities(state, {configured: true, pending: false});
  assert(cards.includes('Saved possibilities (1)'));
  assert.equal((cards.match(/data-view-direction=/g) || []).length, 3);
  const {renderUtility,readingPages}=await import('../../src/features/workspace/views.js');
  const {renderWorkspace}=await import('../../src/features/workspace/screen.js');
  const presenceState=structuredClone(state); presenceState.designPanel='revision';
  const presence=renderWorkspace(presenceState,{configured:true,pending:false},'', 'presence');
  assert(presence.includes('proactive check-ins') && presence.includes('realistic for your workload'), 'Instructor presence asks about responsive and sustainable teaching');
  assert.equal((renderUtility(state,{configured:true},{screen:'combine'}).match(/data-combine-direction=/g)||[]).length,3);
  const source='### A heading\n\n'+('A sentence with evidence. '.repeat(100));
  assert.equal(readingPages(source,120).join(''),source.trim(),'Reading sections preserve original text and line breaks');
  assert(readingPages(source,120).length>1);
  assert(!cards.includes('<details')); 
  const hostile = structuredClone(state);
  hostile.creative.directions[0].title = '<script>alert(1)</script>';
  assert(!renderPossibilities(hostile, {configured: true}).includes('<script>'));
  assert(!renderCreativeCore(state).includes('data-action="hear-maya"'), 'Paused invitations stay hidden');
  state.creative.mayaPaused = false;
  assert(renderUtility(state,{},{screen:'maya'}).includes('data-action="hear-maya"'));
  const guide = createGuide(state.design, { teacher: state.teacher, workspace: state.workspace });
  for (const text of [state.workspace.creativeCore, state.workspace.instructorPlan, state.workspace.openQuestions]) assert(guide.includes(text));
  const guidedRequest = buildBabbageRequest(initialState(discussionOpening), 'clarify');
  assert(!guidedRequest.system.includes('workspace.selectedDirection'));
  assert(buildCreativeRequest(state).system.includes('ONLY JSON'));
  const approvalState = freshWorkspace();
  approvalState.teacher.directions = 'Use a discussion.';
  approvalState.design.revision = 'Students explain and revise a decision.';
  approvalState.design.reason = 'The exchange makes reasoning visible.';
  approvalState.teacher.learningGoal = 'Evaluate evidence.';
  approvalState.finalCheck = {
    ...approvalState.finalCheck,
    instructions: true,
    learning: true,
    requirements: true,
  };
  approvalState.finalCheck.context = finalCheckContext(approvalState.teacher, approvalState.design);
  assert(finalCheckReady(approvalState), 'Final approval remains available with a meaningful learning goal');
  approvalState.teacher.learningGoal = '';
  approvalState.finalCheck.context = finalCheckContext(approvalState.teacher, approvalState.design);
  assert(!finalCheckReady(approvalState), 'Final approval remains blocked without a learning goal');
  console.log('PASS: creative service contract, malformed and duplicate responses, cancellation, stale context, combinations, independent persistence, legacy and corrupt saves, escaping, optional Maya, guide intentions, guided prompt isolation. Mocked service only.');
})().catch(error => { console.error(error); process.exitCode = 1; });
